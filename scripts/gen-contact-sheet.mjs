#!/usr/bin/env node
/**
 * Builds docs/visuals/contact-sheet.html from whatever's currently on disk in
 * static/visuals/ — every lens image large, then each question's options
 * grouped with their label underneath. Missing files are left as an empty,
 * labelled dashed box rather than a placeholder image, so a partial
 * generation run is still an honest sheet, not a fake-complete one.
 */
import { register } from 'node:module';
import { writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
register('./ts-ext-loader.mjs', import.meta.url);
const ROOT = join(__dirname, '..');

const { FUTURES } = await import('../src/lib/game/futures.ts');
const { QUESTIONS } = await import('../src/lib/game/questions.ts');

function esc(s) {
	return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function img(relPath, alt) {
	const abs = join(ROOT, 'static', relPath);
	if (!existsSync(abs)) {
		return `<div class="missing" title="${esc(alt)}">missing<br>${esc(relPath)}</div>`;
	}
	return `<img src="../../static${relPath}" alt="${esc(alt)}" loading="lazy">`;
}

const lensSection = FUTURES.map(
	(f) => `
	<figure class="lens">
		${img(`/visuals/lens/${f.key}.jpg`, f.name)}
		<figcaption><strong>${esc(f.name)}</strong><br>${esc(f.blurb)}</figcaption>
	</figure>`
).join('\n');

const questionSections = QUESTIONS.map((q) => {
	const cells = q.options
		.filter((o) => !o.open)
		.map(
			(o) => `
		<figure class="opt">
			${img(`/visuals/opt/${q.id}-${o.key}.jpg`, o.label)}
			<figcaption>${esc(o.label)}</figcaption>
		</figure>`
		)
		.join('\n');
	return `
	<section class="question">
		<h2>${esc(q.id.toUpperCase())} — ${esc(q.prompt)}</h2>
		<div class="grid opt-grid">${cells}</div>
	</section>`;
}).join('\n');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>z-interact-v4 — visuals contact sheet</title>
<style>
	:root { color-scheme: dark; }
	body { background:#111; color:#eee; font-family: -apple-system, system-ui, sans-serif; margin: 0; padding: 32px; }
	h1 { font-size: 22px; margin-bottom: 4px; }
	p.sub { color: #999; margin-top: 0; }
	h2 { font-size: 16px; margin: 32px 0 12px; border-top: 1px solid #333; padding-top: 16px; }
	.grid { display: grid; gap: 16px; }
	.lens-grid { grid-template-columns: repeat(auto-fill, minmax(280px, 1fr)); margin-bottom: 40px; }
	.opt-grid { grid-template-columns: repeat(auto-fill, minmax(160px, 1fr)); }
	figure { margin: 0; }
	figure img { width: 100%; height: auto; display: block; border-radius: 6px; background: #222; }
	figure.lens img { aspect-ratio: 4/3; object-fit: cover; }
	figure.opt img { aspect-ratio: 1/1; object-fit: cover; }
	figcaption { font-size: 12px; color: #ccc; margin-top: 6px; line-height: 1.3; }
	.missing { aspect-ratio: 1/1; border: 1px dashed #555; border-radius: 6px; display: flex; align-items: center; justify-content: center; color: #666; font-size: 11px; text-align: center; padding: 8px; }
	figure.lens .missing { aspect-ratio: 4/3; }
</style>
</head>
<body>
	<h1>Visuals contact sheet</h1>
	<p class="sub">Generated by scripts/gen-contact-sheet.mjs — 7 futures, ${QUESTIONS.reduce((n, q) => n + q.options.filter((o) => !o.open).length, 0)} options.</p>
	<div class="grid lens-grid">${lensSection}</div>
	${questionSections}
</body>
</html>
`;

await writeFile(join(ROOT, 'docs/visuals/contact-sheet.html'), html);
console.log('wrote docs/visuals/contact-sheet.html');
